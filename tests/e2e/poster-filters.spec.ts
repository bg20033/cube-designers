import AxeBuilder from "@axe-core/playwright"
import { expect, test } from "@playwright/test"

test("Seria contains poster facets, sorting, price and favorites in one popup", async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem("cube-shop-favorites-v1", JSON.stringify(["orbit"])))
  await page.goto("/shop?category=Postera")
  const toolbar = page.locator(".cube-shop-toolbar")
  const trigger = toolbar.getByRole("button", { name: /^Seria/ })
  await expect(toolbar.getByRole("button")).toHaveCount(1)
  await expect(toolbar.getByRole("combobox")).toHaveCount(0)
  await expect(page.locator(".cube-filter-button, .cube-filter-panel")).toHaveCount(0)
  await trigger.click()
  const panel = page.locator(".filter-menu-panel")
  await expect(panel.getByRole("group", { name: "Dekada", exact: true })).toBeVisible()
  const sort = panel.getByRole("combobox", { name: "Rendit produktet: Postera" })
  await sort.selectOption("price-low")
  await expect(page).toHaveURL(/sort=price-low/)
  const price = panel.getByRole("slider", { name: "Çmimi maksimal" })
  await price.focus()
  await price.press("Home")
  await price.press("ArrowRight")
  await price.press("ArrowRight")
  await expect(page).toHaveURL(/max=10/)
  await expect(page.locator(".cube-shop-grid .cube-product-card").first()).toBeVisible()
  await panel.getByRole("button", { name: "Vetëm të ruajturat (1)", exact: true }).click()
  await expect(page).toHaveURL(/saved=1/)
  await panel.getByRole("button", { name: "Pastro", exact: true }).click()
  await expect(page).toHaveURL(/category=Postera$/)
  await expect(sort).toHaveValue("featured")
  await expect(panel.getByRole("button", { name: "Pastro", exact: true })).toBeDisabled()
  await panel.getByRole("group", { name: "Dekada", exact: true }).locator("label").first().click()
  await expect(page).toHaveURL(/dekada=/)
  const results = await new AxeBuilder({ page }).include(".cube-shop-toolbar").withTags(["wcag2a", "wcag2aa"]).analyze()
  expect(results.violations.filter((violation) => ["serious", "critical"].includes(violation.impact ?? ""))).toEqual([])
  await panel.getByRole("button", { name: "Gati", exact: true }).click()
  await expect(panel).toHaveCount(0)
  await expect(trigger).toBeFocused()
  await expect(trigger).toHaveClass(/is-active/)
  await page.reload()
  await expect(trigger).toHaveClass(/is-active/)
})
