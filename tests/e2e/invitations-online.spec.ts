import { expect, test } from "@playwright/test"
test.use({ permissions: ["clipboard-read", "clipboard-write"] })
test("Neon order flow: organizer, admin and guest share durable data across isolated sessions", async ({ page, browser }) => {
  const organizerLast = `Organizatori ${test.info().project.name}`
  const failures: string[] = []
  page.on("pageerror", (error) => failures.push(error.message))
  await page.goto("/ftesa")
  await page.getByLabel("Emri", { exact: true }).fill("Test")
  await page.getByLabel("Mbiemri", { exact: true }).fill(organizerLast)
  await page.getByLabel("Emaili", { exact: true }).fill(`${test.info().project.name}@example.test`)
  await page.getByRole("button", { name: "Dërgo kërkesën", exact: true }).click()
  await expect(page.getByRole("heading", { name: "Kërkesa u dërgua.", exact: true })).toBeVisible({ timeout: 20000 })
  const adminContext = await browser.newContext({ baseURL: "http://127.0.0.1:4178", viewport: page.viewportSize()!, permissions: ["clipboard-read", "clipboard-write"] })
  const guestContext = await browser.newContext({ viewport: page.viewportSize()! })
  const secondOwnerContext = await browser.newContext({ baseURL: "http://127.0.0.1:4178", viewport: page.viewportSize()! })
  try {
    const admin = await adminContext.newPage()
    await admin.goto("/admin")
    await admin.getByLabel("Fjalëkalimi").fill("browser-test-admin-password")
    await admin.getByRole("button", { name: "Kyçu", exact: true }).click()
    await admin.getByRole("navigation").getByRole("button", { name: "Ftesat" }).click()
    await admin.locator(".admin-list").getByRole("button", { name: new RegExp(`Test ${organizerLast}`) }).first().click()
    await admin.getByLabel("Emrat e çiftit", { exact: true }).fill("Test Çifti & Hana")
    await admin.getByLabel("Data e dasmës", { exact: true }).fill("2027-06-20")
    await admin.getByRole("button", { name: "Krijo llogarinë", exact: true }).click()
    await expect(admin.getByRole("heading", { name: "Të dhënat e kyçjes", exact: true })).toBeVisible()
    const accessPassword = await admin.getByLabel("Fjalëkalimi i klientit", { exact: true }).inputValue()
    const reference = await admin.locator(".admin-detail h2").innerText()
    expect(reference).toMatch(/^FTE-/)
    await admin.getByRole("button", { name: "Kopjo të dhënat", exact: true }).click()
    await expect(admin.getByRole("button", { name: "U kopjuan", exact: true })).toBeVisible()
    const instructions = await admin.evaluate(() => navigator.clipboard.readText())
    expect(instructions).toContain(reference)
    expect(instructions).toContain(accessPassword)
    await page.goto("/ftesa?view=login")
    await page.getByLabel("Referenca e porosisë", { exact: true }).fill(reference)
    await page.getByLabel("Fjalëkalimi", { exact: true }).fill(accessPassword)
    await page.getByRole("button", { name: "Kyçu në dashboard", exact: true }).click()
    await expect(page.getByRole("heading", { name: /Porosia u ruajt/ })).toBeVisible()
    admin.once("dialog", (dialog) => dialog.accept())
    await admin.getByRole("button", { name: "Konfirmo pagesën dhe aktivizo" }).click()
    await expect(admin.getByText("E konfirmuar nga admini", { exact: true })).toBeVisible()

    await page.getByRole("button", { name: "Kontrollo aktivizimin" }).click()
    await expect(page.getByRole("heading", { level: 1 })).toContainText("Test Çifti & Hana")
    await page.getByRole("navigation", { name: "Navigimi i ftesave" }).getByRole("button", { name: "Planifikimi", exact: true }).click()
    await page.getByRole("region", { name: "Video & foto", exact: true }).getByRole("button", { name: "Shto", exact: true }).click()
    await page.getByRole("dialog").getByLabel("Emri", { exact: true }).fill("Private wedding studio")
    await page.getByRole("dialog").getByLabel("Çmimi (€)").fill("900")
    await page.getByRole("dialog").getByLabel("Paguar deri tani (€)").fill("100")
    await page.getByRole("dialog").getByLabel("Si u morëm vesh").fill("CONFIDENTIAL COUPLE NOTE")
    await page.getByRole("dialog").getByRole("button", { name: "Ruaj", exact: true }).click()
    await expect(page.getByTestId("budget-total")).toContainText("900,00")
    await page.getByRole("navigation", { name: "Navigimi i ftesave" }).getByRole("button", { name: "Mysafirët", exact: true }).click()
    await page.getByRole("button", { name: "Shto mysafir", exact: true }).click()
    await page.getByLabel("Emri në ftesë").fill("Familja Online")
    await page.getByLabel("Vendet", { exact: true }).fill("3")
    await page.getByRole("button", { name: "Krijo dhe kopjo linkun", exact: true }).click()
    await page.getByRole("button", { name: "Kopjo linkun për Familja Online", exact: true }).click()
    const link = await page.evaluate(() => navigator.clipboard.readText())
    expect(link).toMatch(/#ftesa=[a-f0-9]{64}$/)

    const guest = await guestContext.newPage()
    await guest.goto(link)

    await expect(guest.getByRole("heading", { name: "Familja Online", exact: true })).toBeVisible()
    await expect(guest.getByText("CONFIDENTIAL COUPLE NOTE")).toHaveCount(0)
    await expect(guest.getByText("Private wedding studio")).toHaveCount(0)
    await expect(guest.getByRole("heading", { name: "Kanagjegji", exact: true })).toHaveCount(0)
    await guest.getByRole("button", { name: "Do të vijmë" }).click()
    await guest.getByLabel("Numri i personave për Dasma").selectOption("2")
    await guest.getByRole("button", { name: "Konfirmo pjesëmarrjen" }).click()
    await expect(guest.getByRole("button", { name: "Përgjigjja u ruajt" })).toBeVisible()
    await page.getByRole("button", { name: "Rifresko", exact: true }).click()
    await page.getByRole("navigation", { name: "Navigimi i ftesave" }).getByRole("button", { name: "Kryefaqja", exact: true }).click()
    await expect(page.getByRole("article", { name: "Dasma", exact: true }).locator(".inv-attendance-main strong")).toHaveText("2")

    const secondOwner = await secondOwnerContext.newPage()
    await secondOwner.goto("/ftesa")
    await secondOwner.getByRole("navigation", { name: "Ftesa online", exact: true }).getByRole("link", { name: "Kyçu", exact: true }).click()
    await secondOwner.getByLabel("Referenca e porosisë").fill(reference)
    await secondOwner.getByLabel("Fjalëkalimi", { exact: true }).fill(accessPassword)
    await secondOwner.getByRole("button", { name: "Kyçu në dashboard" }).click()
    await expect(secondOwner.getByRole("article", { name: "Dasma", exact: true }).locator(".inv-attendance-main strong")).toHaveText("2")
    await secondOwner.getByRole("navigation", { name: "Navigimi i ftesave" }).getByRole("button", { name: "Planifikimi", exact: true }).click()
    await expect(secondOwner.getByText("CONFIDENTIAL COUPLE NOTE")).toBeVisible()
    await expect(secondOwner.getByTestId("budget-total")).toContainText("900,00")
    await expect(secondOwner.getByTestId("budget-outstanding")).toContainText("800,00")
    await secondOwner.getByRole("navigation", { name: "Navigimi i ftesave" }).getByRole("button", { name: "Ftesa", exact: true }).click()
    await secondOwner.getByRole("button", { name: /Nën yje/ }).click()
    await secondOwner.getByRole("button", { name: "Ruaj ftesën", exact: true }).click()
    await expect(secondOwner.getByRole("button", { name: "Ruaj ftesën", exact: true })).toBeDisabled()
    await guest.reload()
    await expect(guest.locator(".inv-card")).toHaveClass(/inv-theme-midnight/)
    await expect(guest.getByLabel("Numri i personave për Dasma")).toHaveValue("2")

    // A single general link registers a new family from an isolated browser,
    // then gives that family its own private link for later RSVP edits.
    await page.getByRole("button", { name: "Rifresko", exact: true }).click()
    await page.getByRole("navigation", { name: "Navigimi i ftesave" }).getByRole("button", { name: "Mysafirët", exact: true }).click()
    await page.getByRole("button", { name: "Linku për të gjithë", exact: true }).click()
    await page.getByLabel("Maksimumi i personave për një konfirmim").selectOption("3")
    await page.getByRole("button", { name: "Ruaj dhe kopjo linkun", exact: true }).click()
    await expect(page.getByRole("dialog")).toHaveCount(0)
    const generalUrl = await page.evaluate(() => navigator.clipboard.readText())
    expect(generalUrl).toMatch(/#teftuar=[a-f0-9]{64}$/)
    const generalContext = await browser.newContext({ viewport: page.viewportSize()! })
    try {
      const generalGuest = await generalContext.newPage()
      await generalGuest.goto(generalUrl)
      await expect(generalGuest.getByLabel("Emri yt ose i familjes")).toBeVisible()
      await expect(generalGuest.getByText("CONFIDENTIAL COUPLE NOTE")).toHaveCount(0)
      await expect(generalGuest.getByRole("heading", { name: "Kanagjegji", exact: true })).toHaveCount(0)
      await generalGuest.getByLabel("Emri yt ose i familjes").fill("Familja nga master linku")
      await generalGuest.getByLabel("Numri i personave", { exact: true }).selectOption("2")
      await generalGuest.getByRole("button", { name: "Do të vijmë", exact: true }).click()
      await generalGuest.getByRole("button", { name: "Konfirmo pjesëmarrjen", exact: true }).click()
      await expect(generalGuest).toHaveURL(/#ftesa=[a-f0-9]{64}$/)
      await expect(generalGuest.getByRole("heading", { name: "Familja nga master linku", exact: true })).toBeVisible()
      await expect(generalGuest.getByRole("button", { name: "Përgjigjja u ruajt" })).toBeVisible()
      await generalGuest.reload()
      await expect(generalGuest.getByLabel("Numri i personave për Dasma")).toHaveValue("2")
      await page.getByRole("button", { name: "Rifresko", exact: true }).click()
      await expect(page.getByRole("button", { name: "Kopjo linkun për Familja nga master linku", exact: true })).toBeVisible()
      await page.getByRole("button", { name: "Linku për të gjithë", exact: true }).click()
      await page.getByLabel("Linku është aktiv").uncheck()
      await page.getByRole("button", { name: "Ruaj ndryshimet", exact: true }).click()
      await expect(page.getByRole("dialog")).toHaveCount(0)
      await generalGuest.goto(generalUrl)
      await expect(generalGuest.getByRole("heading", { level: 1 })).toHaveText("Kjo ftesë nuk hapet.")
    } finally { await generalContext.close() }

    await admin.getByLabel("Statusi i paketës").selectOption("suspended")
    await expect(admin.getByLabel("Statusi i paketës")).toHaveValue("suspended")
    await guest.reload()
    await expect(guest.getByRole("heading", { level: 1 })).toHaveText("Kjo ftesë nuk hapet.")
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    expect(failures).toEqual([])
  } finally { await adminContext.close(); await guestContext.close(); await secondOwnerContext.close() }
})


test("admin reviews requests, creates accounts and can reset or suspend access", async ({ page }) => {
  const surname = `Review ${test.info().project.name}`
  await page.goto("/ftesa?view=apply")
  await page.getByLabel("Emri", { exact: true }).fill("Kontroll")
  await page.getByLabel("Mbiemri", { exact: true }).fill(surname)
  await page.getByLabel("Emaili", { exact: true }).fill(`review-${test.info().project.name}@example.test`)
  await page.getByRole("button", { name: "Dërgo kërkesën", exact: true }).click()
  await expect(page.getByRole("heading", { name: "Kërkesa u dërgua.", exact: true })).toBeVisible({ timeout: 20000 })
  await page.goto("/admin")
  await page.getByLabel("Fjalëkalimi", { exact: true }).fill("browser-test-admin-password")
  await page.getByRole("button", { name: "Kyçu", exact: true }).click()
  await page.getByRole("navigation").getByRole("button", { name: "Ftesat", exact: true }).click()
  await page.locator(".admin-list").getByRole("button", { name: new RegExp(`Kontroll ${surname}`) }).click()
  await page.getByRole("button", { name: "Refuzo kërkesën", exact: true }).click()
  await expect(page.getByRole("button", { name: "Rihap kërkesën", exact: true })).toBeVisible()
  await expect(page.getByRole("button", { name: "Krijo llogarinë", exact: true })).toHaveCount(0)
  await page.reload()
  await page.getByRole("navigation").getByRole("button", { name: "Ftesat", exact: true }).click()
  await page.locator(".admin-list").getByRole("button", { name: new RegExp(`Kontroll ${surname}`) }).click()
  await page.getByRole("button", { name: "Rihap kërkesën", exact: true }).click()
  await page.getByLabel("Emrat e çiftit", { exact: true }).fill("Kontroll & Hana")
  await page.getByLabel("Data e dasmës", { exact: true }).fill("2027-07-15")
  await page.getByRole("checkbox", { name: /Pagesa u konfirmua/ }).check()
  await page.getByRole("button", { name: "Krijo llogarinë", exact: true }).click()
  await expect(page.getByRole("heading", { name: "Të dhënat e kyçjes", exact: true })).toBeVisible()
  const oldPassword = await page.getByLabel("Fjalëkalimi i klientit").inputValue()
  const reference = await page.locator(".admin-detail h2").innerText()
  const draft = new URL((await page.getByRole("link", { name: "Përgatit emailin", exact: true }).getAttribute("href"))!)
  expect(draft.searchParams.get("body")).toContain(reference)
  expect(draft.searchParams.get("body")).toContain(oldPassword)
  expect((await page.request.post("/api/invitation-session", { data: { reference, password: oldPassword } })).status()).toBe(200)
  page.once("dialog", (dialog) => dialog.accept())
  await page.getByRole("button", { name: "Ndrysho fjalëkalimin", exact: true }).click()
  await expect(page.getByLabel("Fjalëkalimi i klientit")).not.toHaveValue(oldPassword)
  expect((await page.request.get("/api/invitations")).status()).toBe(401)
  await page.getByLabel("Statusi i paketës", { exact: true }).selectOption("suspended")
  await expect(page.locator(".admin-detail select").first()).toHaveValue("suspended")
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(page.viewportSize()!.width)
})
