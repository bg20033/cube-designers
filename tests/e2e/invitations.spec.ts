test("copy remains direct when the Clipboard API is denied, for personal, bulk and general links", async ({ page }) => {
  await page.goto("/ftesa?demo=1&tab=guests")
  await page.evaluate(async () => {
    await navigator.clipboard.writeText("previous clipboard value")
    Object.defineProperty(navigator.clipboard, "writeText", { configurable: true, value: async () => { throw new Error("Clipboard API denied") } })
  })
  await page.getByRole("button", { name: "Kopjo linkun për Familja Gashi", exact: true }).click()
  await expect(page.getByRole("status")).toContainText("Linku personal u kopjua")
  const personal = await page.evaluate(() => navigator.clipboard.readText())
  expect(personal).toContain("#ftese=")
  const snapshot = JSON.parse(Buffer.from(new URLSearchParams(new URL(personal).hash.slice(1)).get("ftese")!, "base64").toString("utf8"))
  expect(snapshot.guest.name).toBe("Familja Gashi")
  await expect(page.getByRole("dialog")).toHaveCount(0)
  await page.getByRole("button", { name: "Kopjo të gjitha linket", exact: true }).click()
  expect((await page.evaluate(() => navigator.clipboard.readText())).match(/#ftese=/g)).toHaveLength(8)
  await expect(page.getByRole("dialog")).toHaveCount(0)
  await page.getByRole("navigation", { name: "Navigimi i ftesave" }).getByRole("button", { name: "Kryefaqja", exact: true }).click()
  await page.getByRole("button", { name: "Kopjo linkun", exact: true }).click()
  await expect(page.getByRole("status")).toContainText("Linku për të gjithë u kopjua")
  expect(await page.evaluate(() => navigator.clipboard.readText())).toContain("#teftuar-demo=")
  await expect(page.getByRole("dialog")).toHaveCount(0)
  expect(await page.locator("textarea[aria-hidden=true]").count()).toBe(0)
})

