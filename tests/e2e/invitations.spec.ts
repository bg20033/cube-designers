test("personal link opens in a separate browser context without exposing the guest list", async ({ page, browser }) => {
  // A fresh context behaves like a pristine demo, where Familja Gashi already has answers, so use a guest who has not answered yet.
  await page.goto("/ftesa?demo=1")
  await page.getByRole("navigation", { name: "Navigimi i ftesave" }).getByRole("button", { name: "Mysafirët", exact: true }).click()
  await page.getByRole("button", { name: "Kopjo linkun për Familja Krasniqi", exact: true }).click()
  const link = await page.evaluate(() => navigator.clipboard.readText())
  const guestContext = await browser.newContext({ viewport: page.viewportSize()! })
  try {
    const guestPage = await guestContext.newPage()
    await guestPage.goto(link)

    await expect(guestPage.getByRole("heading", { name: "Familja Krasniqi", exact: true })).toBeVisible()
    await expect(guestPage.getByText("Familja Gashi")).toHaveCount(0)
    await expect(guestPage.getByRole("navigation", { name: "Navigimi i ftesave" })).toHaveCount(0)
    await expect(guestPage.getByRole("heading", { name: "Kanagjegji", exact: true })).toHaveCount(0)
    await guestPage.getByRole("button", { name: "Konfirmo pjesëmarrjen" }).click()
    await expect(guestPage.getByRole("alert")).toContainText("secilin event")
    await guestPage.getByRole("button", { name: "S’mund të vijmë" }).first().click()
    await guestPage.getByRole("button", { name: "Do të vijmë" }).last().click()
    await guestPage.getByLabel("Numri i personave për Dasma").selectOption("3")
    await guestPage.getByRole("button", { name: "Konfirmo pjesëmarrjen" }).click()
    await guestPage.reload()
    await expect(guestPage.getByLabel("Numri i personave për Dasma")).toHaveValue("3")
    expect(await guestPage.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  } finally { await guestContext.close() }
})

