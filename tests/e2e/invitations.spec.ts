import { expect, test } from "@playwright/test"
test.use({ permissions: ["clipboard-read", "clipboard-write"] })
import { readFile } from "node:fs/promises"

test("the simple invitation opens directly and exports the selected calendar event", async ({ page }) => {
  await page.goto("/ftesa?demo=1&preview=1")
  await expect(page.getByRole("heading", { level: 1 })).toContainText("Arbër")
  await expect(page.getByRole("button", { name: "Hape ftesën", exact: true })).toHaveCount(0)
  await expect(page.getByRole("heading", { name: "Familja Gashi", exact: true })).toBeVisible()
  const downloadEvent = page.waitForEvent("download")
  await page.getByRole("button", { name: "Shto Nata e dasmës në kalendar", exact: true }).click()
  const download = await downloadEvent
  expect(download.suggestedFilename()).toBe("ftesa-nata.ics")
  const calendar = await readFile((await download.path())!, "utf8")
  expect(calendar).toContain("BEGIN:VCALENDAR")
  expect(calendar).toContain("DTSTART:20270619T180000Z")
  expect(calendar).not.toContain("Familja Krasniqi")
  await page.reload()
  await expect(page.getByRole("heading", { level: 1 })).toContainText("Hana")
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
})

