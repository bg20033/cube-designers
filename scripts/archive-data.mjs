// Writes src/data/archive-posters.ts in a compact form: posters grouped by
// series, each as [slug without the series prefix, title, year, scan width].
// About half the size of one object per poster, which matters because the
// whole list ships with the shop.
const PREFIX = {
  Kinema: "kinema",
  Muzikë: "muzike",
  Teatër: "teater",
  Nota: "nota",
  Udhëtim: "udhetim",
  "Belle Époque": "belle-epoque",
}

export function formatArchiveData(entries, latestYear) {
  const groups = new Map()
  for (const { slug, series, title, year, width } of entries) {
    const prefix = PREFIX[series]
    if (!prefix || !slug.startsWith(`${prefix}-`))
      throw new Error(`Unexpected slug for ${series}: ${slug}`)
    if (!groups.has(series)) groups.set(series, [])
    groups.get(series).push([slug.slice(prefix.length + 1), title, year, width])
  }
  const body = [...groups]
    .map(
      ([series, rows]) =>
        `  [${JSON.stringify(series)}, ${JSON.stringify(PREFIX[series])}, [\n${rows
          .map((row) => `    ${JSON.stringify(row)},`)
          .join("\n")}\n  ]],`,
    )
    .join("\n")
  return `// Generated by scripts/fetch-commons-posters.mjs — public-domain posters
// (published before ${latestYear + 1}) from Wikimedia Commons and the Internet
// Archive. Re-run the script instead of editing. Artist and source page for
// every slug: docs/archive-poster-sources.json.

export type ArchivePoster = {
  slug: string
  series: string
  title: string
  year: number
  // Width of the original scan in px; decides which print sizes are sold.
  width: number
}

// [series, slug prefix, [slug, title, year, width][]]
type Row = [string, string, number, number]
const data: [string, string, Row[]][] = [
${body}
]

export const archivePosters: ArchivePoster[] = data.flatMap(
  ([series, prefix, rows]) =>
    rows.map(([slug, title, year, width]) => ({
      slug: \`\${prefix}-\${slug}\`,
      series,
      title,
      year,
      width,
    })),
)
`
}
